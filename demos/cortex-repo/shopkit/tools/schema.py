"""Read schema/models.yaml and render the derived files."""

import hashlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema" / "models.yaml"
TYPES = {"int": "int", "str": "str", "bool": "bool", "float": "float"}
SQL = {"int": "INTEGER", "str": "TEXT", "bool": "INTEGER", "float": "REAL"}


def load():
    models = yaml.safe_load(SCHEMA.read_text())["models"]
    for name, model in models.items():
        for field, spec in model["fields"].items():
            if spec.get("type") not in TYPES:
                raise SystemExit(f"schema: {name}.{field} has unsupported type {spec.get('type')!r}")
    return models


def digest():
    return hashlib.sha256(SCHEMA.read_bytes()).hexdigest()[:12]


def python_default(spec):
    if "default" not in spec:
        return "None" if not spec.get("primary") else None
    return repr(spec["default"])


def render_models(models):
    lines = [f"# GENERATED by `make generate` from schema/models.yaml (schema {digest()}). Do not edit.", ""]
    lines += ["from dataclasses import dataclass", "", f'SCHEMA_DIGEST = "{digest()}"', ""]
    for name, model in models.items():
        lines += ["", "@dataclass", f"class {name}:"]
        required = [(f, s) for f, s in model["fields"].items() if s.get("primary")]
        optional = [(f, s) for f, s in model["fields"].items() if not s.get("primary")]
        for field, spec in required:
            lines.append(f"    {field}: {TYPES[spec['type']]}")
        for field, spec in optional:
            lines.append(f"    {field}: {TYPES[spec['type']]} | None = {python_default(spec)}")
        lines.append("")
    lines += ["", "TABLES = {" + ", ".join(f'"{m["table"]}": {n}' for n, m in models.items()) + "}", ""]
    return "\n".join(lines)


def render_client(models):
    lines = [f"# GENERATED by `make generate` from schema/models.yaml (schema {digest()}). Do not edit.", ""]
    lines += [f'SCHEMA_DIGEST = "{digest()}"', "", "FIELDS = {"]
    for name, model in models.items():
        lines.append(f'    "{name}": {list(model["fields"])!r},')
    lines += ["}", "", "", "def payload(model, **values):", '    """Validate a request body against the generated field list."""']
    lines += ["    unknown = set(values) - set(FIELDS[model])", "    if unknown:"]
    lines += ['        raise ValueError(f"{model} has no field(s): {sorted(unknown)}")', "    return values", ""]
    return "\n".join(lines)


def columns(models):
    """Expected database columns per table, in schema order."""
    return {model["table"]: {field: SQL[spec["type"]] for field, spec in model["fields"].items()} for model in models.values()}
